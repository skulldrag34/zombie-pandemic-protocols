// Item art: embedded WebP cards built by tools/build_art.py.
// Checks the data (every image is a real item, decodes as WebP, sized as the manifest says, within
// the file budget), the stylesheet built at startup, and that cards show art when an item has it
// and render unchanged when it does not (art arrives in batches).
const fs = require('fs');
const path = require('path');
const H = require('./harness.js');
const { $, q, tab, click, clickEl, loadSave, sleep, baseSave, makeChecker } = H;

const GAME = fs.readFileSync(H.GAME_PATH, 'utf8');
const MANIFEST = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'tools', 'art_manifest.json'), 'utf8'));
const ART_BUDGET_BYTES = 3 * 1024 * 1024;   // whole game file, all art included (designer chose embedding)

// Minimal WebP header reader: VP8 (lossy), VP8L (lossless) or VP8X (extended).
function webpSize(buf) {
  if (buf.toString('ascii', 0, 4) !== 'RIFF' || buf.toString('ascii', 8, 12) !== 'WEBP') return null;
  const chunk = buf.toString('ascii', 12, 16);
  if (chunk === 'VP8 ') return { w: buf.readUInt16LE(26) & 0x3fff, h: buf.readUInt16LE(28) & 0x3fff };
  if (chunk === 'VP8L') { const b = buf.readUInt32LE(21); return { w: (b & 0x3fff) + 1, h: ((b >> 14) & 0x3fff) + 1 }; }
  if (chunk === 'VP8X') return { w: buf.readUIntLE(24, 3) + 1, h: buf.readUIntLE(27, 3) + 1 };
  return null;
}

// JPEG size from the first SOF marker.
function jpegSize(file) {
  if (!fs.existsSync(file)) return null;
  const b = fs.readFileSync(file);
  if (b[0] !== 0xff || b[1] !== 0xd8) return null;
  let i = 2;
  while (i < b.length) {
    if (b[i] !== 0xff) return null;
    const m = b[i + 1], len = b.readUInt16BE(i + 2);
    if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) return { h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7) };
    i += 2 + len;
  }
  return null;
}

async function session(saveObj) { const s = H.makeSession(); loadSave(s.window, saveObj); await sleep(300); return s; }

(async () => {
  const c = makeChecker('ITEM ART');
  const errors = [];
  const done = (s) => { errors.push(...s.errors); s.close(); };

  console.log('A) Embedded data');
  const s0 = await session(baseSave());
  const w0 = s0.window;
  const items = (w0.ZP_ART && w0.ZP_ART.items) || {};
  const names = Object.keys(items);
  c.ok(names.length === Object.keys(MANIFEST.items).length, `every manifest entry is embedded (${names.length}/${Object.keys(MANIFEST.items).length})`);
  const bad = [];
  for (const n of names) {
    const m = /^data:image\/webp;base64,([A-Za-z0-9+/=]+)$/.exec(items[n]);
    const sz = m && webpSize(Buffer.from(m[1], 'base64'));
    if (!sz || sz.w !== MANIFEST.size || sz.h !== MANIFEST.size) bad.push(`${n}: ${sz ? sz.w + 'x' + sz.h : 'not WebP'}`);
  }
  c.ok(bad.length === 0, `every image is a ${MANIFEST.size}x${MANIFEST.size} WebP${bad.length ? ' (bad: ' + bad.join(', ') + ')' : ''}`);
  const style = w0.document.getElementById('zp-item-art');
  const classes = style ? (style.textContent.match(/\.ia\d+\{/g) || []).length : 0;
  c.ok(classes === names.length, `one CSS class per image, so every embedded name is a real item (${classes}/${names.length})`);
  const bytes = Buffer.byteLength(GAME, 'utf8');
  c.ok(bytes < ART_BUDGET_BYTES, `game file stays under the 3 MB budget (${Math.round(bytes / 1024)} KB)`);
  const artBlock = /<script id="zp-art">([\s\S]*?)<\/script>/.exec(GAME);
  c.ok(artBlock && /generated by tools\/build_art\.py/.test(artBlock[1]), 'art lives in its own generated script block');
  done(s0);

  console.log('B) Cards show art when an item has it');
  const inv = { 'Bandage': 2, 'Crowbar': 1, 'Pistol': 1, 'Medkit': 1, 'Cloth Strips': 4, 'Bandana': 1, 'Shotgun': 1, 'Riot Armor': 1, 'Padded Leg Guards': 1 };
  let s = await session(baseSave({ inventory: inv, equippedWeapon: 'Crowbar', equipment: { head: 'Bandana', torso: null, hands: null, pants: null, feet: null } }));
  let w = s.window;
  tab(w, 'inventory');
  const artIn = (root, n) => !!root.querySelector(`[data-art="${n}"]`);
  const grid = $(w, 'invGrid');
  c.ok(artIn(grid, 'Bandage') && artIn(grid, 'Crowbar') && artIn(grid, 'Medkit'), 'inventory: Bandage, Crowbar and Medkit cards show art');
  c.ok(artIn(grid, 'Shotgun') && artIn(grid, 'Riot Armor') && artIn(grid, 'Padded Leg Guards'), 'inventory: batch 2 gear (Shotgun, Riot Armor, Leg Guards) shows art');
  const pistolCard = [...grid.querySelectorAll('.inv-card')].find(e => /Pistol/.test(e.textContent));
  c.ok(pistolCard && !pistolCard.querySelector('.item-art') && !pistolCard.querySelector('.art-row'), 'an item without art (Pistol) renders exactly as before');
  const bArt = grid.querySelector('[data-art="Bandage"]');
  c.ok(bArt.getAttribute('role') === 'img' && bArt.getAttribute('aria-label') === 'Bandage', 'art is labelled for screen readers');
  c.ok(!/data:image/.test(grid.innerHTML), 'cards carry a class name, not image data (cheap 1s re-render)');
  const btn = q(w, '[data-equip="Pistol"]'); clickEl(w, btn);
  c.ok(q(w, '[data-equip="Pistol"]').disabled, 'buttons inside art cards still work');

  tab(w, 'shop');
  const shop = $(w, 'shopContent');
  c.ok(artIn(shop, 'Bandage') && artIn(shop, 'Ammo') && artIn(shop, 'Duct Tape'), 'Safehouse shop: stock cards show art');
  c.ok(artIn($(w, 'shopSellGrid'), 'Medkit'), 'shop sell list shows art');
  const cash0 = parseInt($(w, 'cashNum').textContent, 10);
  clickEl(w, q(w, '[data-buy="Bandage"]'));
  c.ok(parseInt($(w, 'cashNum').textContent, 10) < cash0, 'buying from an art card still works');

  tab(w, 'crafting');
  c.ok(artIn($(w, 'craftList'), 'Bandage') && artIn($(w, 'craftList'), 'Improvised Flamethrower'), 'crafting cards show the art of what they make');

  tab(w, 'character');
  c.ok(artIn($(w, 'characterContent'), 'Bandana'), 'equipment slot shows art for the worn item');
  done(s);

  console.log('C) Title banner and link preview');
  s = H.makeSession(); w = s.window; await sleep(300);
  const title = w.ZP_ART && w.ZP_ART.scenes && w.ZP_ART.scenes.title;
  const tm = title && /^data:image\/webp;base64,([A-Za-z0-9+/=]+)$/.exec(title);
  const tsz = tm && webpSize(Buffer.from(tm[1], 'base64'));
  const TS = MANIFEST.scenes.title;
  c.ok(tsz && tsz.w === TS.w && tsz.h === TS.h, `title banner is a ${TS.w}x${TS.h} WebP (${tsz ? tsz.w + 'x' + tsz.h : 'missing'})`);
  const ta = $(w, 'titleArt');
  c.ok(ta && !ta.classList.contains('hidden') && w.document.getElementById('zp-scene-art'), 'creation screen shows the title banner');
  c.ok(ta.getAttribute('role') === 'img' && /survivor/.test(ta.getAttribute('aria-label')) && !/data:image/.test(ta.outerHTML), 'banner is labelled and carries no image data in markup');
  done(s);
  const meta = (prop) => { const m = new RegExp(`<meta (?:property|name)="${prop}" content="([^"]+)">`).exec(GAME); return m && m[1]; };
  const ogImg = meta('og:image');
  c.ok(ogImg === 'https://skulldrag34.github.io/zombie-pandemic-protocols/og-image.jpg' && meta('twitter:image') === ogImg && meta('twitter:card') === 'summary_large_image', 'link-preview tags point at the hosted og-image.jpg (absolute URL)');
  c.ok(meta('og:title') && meta('og:description') && meta('description'), 'title and descriptions are set');
  const ROOT = path.join(__dirname, '..');
  const og = jpegSize(path.join(ROOT, 'og-image.jpg')), gh = jpegSize(path.join(ROOT, 'docs', 'social-preview.jpg'));
  c.ok(og && og.w === 1200 && og.h === 630 && meta('og:image:width') === '1200' && meta('og:image:height') === '630', `og-image.jpg exists at 1200x630 (${og ? og.w + 'x' + og.h : 'missing'})`);
  c.ok(gh && gh.w === 1280 && gh.h === 640 && /\(docs\/social-preview\.jpg\)/.test(fs.readFileSync(path.join(ROOT, 'README.md'), 'utf8')), 'GitHub banner exists at 1280x640 and heads the README');

  c.done(errors);
})();
