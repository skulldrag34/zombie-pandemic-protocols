#!/usr/bin/env python3
"""Builds the game's embedded item art from art-src/ and tools/art_manifest.json.

Grid sheets are cut into an even 3x3 with an inset that drops the gutters; single images are
used whole. Each card is resized to `size` px, saved as WebP, base64-encoded, and written into
index.html between the ART-DATA markers as `window.ZP_ART = {...}`. Needs Pillow.

    python3 tools/build_art.py            # rebuild index.html in place
    python3 tools/build_art.py --sheet out.png   # also write a contact sheet to check crops
"""
import base64, io, json, os, re, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INSET = 0.045  # fraction of a cell trimmed on every side (removes gutters and cell borders)

def card(entry, size):
    im = Image.open(os.path.join(ROOT, "art-src", entry["src"])).convert("RGB")
    if "cell" in entry:
        r, c = entry["cell"]
        w, h = im.size
        cw, ch = w / 3, h / 3
        dx, dy = cw * INSET, ch * INSET
        im = im.crop((round(c * cw + dx), round(r * ch + dy), round((c + 1) * cw - dx), round((r + 1) * ch - dy)))
    s = min(im.size)  # centre square
    l, t = (im.size[0] - s) // 2, (im.size[1] - s) // 2
    im = im.crop((l, t, l + s, t + s))
    return im.resize((size, size), Image.LANCZOS)

def main():
    man = json.load(open(os.path.join(ROOT, "tools", "art_manifest.json")))
    size, q = man["size"], man["quality"]
    cards, data, total = {}, {}, 0
    for name, entry in man["items"].items():
        im = card(entry, size)
        cards[name] = im
        buf = io.BytesIO()
        im.save(buf, "WEBP", quality=q, method=6)
        b = buf.getvalue()
        total += len(b)
        data[name] = "data:image/webp;base64," + base64.b64encode(b).decode()
    block = "window.ZP_ART = " + json.dumps({"items": data}, separators=(",", ":")) + ";"
    path = os.path.join(ROOT, "index.html")
    html = open(path, encoding="utf-8").read()
    pat = re.compile(r"(<script id=\"zp-art\">/\* ART-DATA: generated by tools/build_art.py, do not edit \*/\n).*?(\n</script>)", re.S)
    if not pat.search(html):
        sys.exit("ART-DATA markers not found in index.html")
    html = pat.sub(lambda m: m.group(1) + block + m.group(2), html)
    open(path, "w", encoding="utf-8").write(html)
    print(f"{len(data)} item cards, {total // 1024} KB WebP ({len(block) // 1024} KB embedded)")
    if "--sheet" in sys.argv:
        out = sys.argv[sys.argv.index("--sheet") + 1]
        n = len(cards); cols = 6; rows = (n + cols - 1) // cols; t = 160
        sheet = Image.new("RGB", (cols * t, rows * t), (20, 20, 20))
        for i, (name, im) in enumerate(cards.items()):
            sheet.paste(im.resize((t - 6, t - 6)), ((i % cols) * t + 3, (i // cols) * t + 3))
        sheet.save(out)
        print("contact sheet:", out)

if __name__ == "__main__":
    main()
