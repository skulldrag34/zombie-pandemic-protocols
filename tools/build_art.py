#!/usr/bin/env python3
"""Builds the game's embedded item art (and wide scene art such as the title banner) from art-src/ and tools/art_manifest.json.

Grid sheets are cut into an even 3x3 with an inset that drops the gutters; single images are
used whole. Enemy portraits (`enemies`, keyed by type) are cropped to 3:4 and resized to 300x400;
companion portraits (`companions`, c1-c12) to 240x320.
Scenes are cropped to their `box` and resized to `w` x `h`. Each card is resized to `size` px, saved as WebP, base64-encoded, and written into
index.html between the ART-DATA markers as `window.ZP_ART = {...}`. Needs Pillow.

    python3 tools/build_art.py            # rebuild index.html in place
    python3 tools/build_art.py --sheet out.png   # also write a contact sheet to check crops
"""
import base64, io, json, os, re, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INSET = 0.045  # fraction of a cell trimmed on every side (removes gutters and cell borders)

def card(entry, size):
    im = Image.open(os.path.join(ROOT, "art-src", entry["src"])).convert("RGB")
    if "cell" in entry:
        r, c = entry["cell"]
        w, h = im.size
        cw, ch = w / 3, h / 3
        dx, dy = cw * INSET, ch * INSET
        im = im.crop((round(c * cw + dx), round(r * ch + dy), round((c + 1) * cw - dx), round((r + 1) * ch - dy)))
    s = min(im.size)  # centre square
    l, t = (im.size[0] - s) // 2, (im.size[1] - s) // 2
    im = im.crop((l, t, l + s, t + s))
    return im.resize((size, size), Image.LANCZOS)

def main():
    man = json.load(open(os.path.join(ROOT, "tools", "art_manifest.json")))
    size, q = man["size"], man["quality"]
    cards, data, total = {}, {}, 0
    for name, entry in man["items"].items():
        im = card(entry, size)
        cards[name] = im
        buf = io.BytesIO()
        im.save(buf, "WEBP", quality=q, method=6)
        b = buf.getvalue()
        total += len(b)
        data[name] = "data:image/webp;base64," + base64.b64encode(b).decode()
    scenes = {}
    for name, entry in man.get("scenes", {}).items():
        im = Image.open(os.path.join(ROOT, "art-src", entry["src"])).convert("RGB")
        im = im.crop(tuple(entry["box"])).resize((entry["w"], entry["h"]), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "WEBP", quality=entry.get("quality", q), method=6)
        b = buf.getvalue()
        total += len(b)
        scenes[name] = "data:image/webp;base64," + base64.b64encode(b).decode()
    enemies = {}
    for key, entry in man.get("enemies", {}).items():
        im = Image.open(os.path.join(ROOT, "art-src", entry["src"])).convert("RGB")
        if "box" in entry:
            im = im.crop(tuple(entry["box"]))
        else:  # centre 3:4, keeping a little more of the top (heads)
            w, h = im.size
            if w * 4 > h * 3:
                cw = h * 3 // 4; im = im.crop(((w - cw) // 2, 0, (w - cw) // 2 + cw, h))
            else:
                ch = w * 4 // 3; top = (h - ch) * 3 // 10; im = im.crop((0, top, w, top + ch))
        im = im.resize((300, 400), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "WEBP", quality=entry.get("quality", q), method=6)
        b = buf.getvalue()
        total += len(b)
        enemies[key] = "data:image/webp;base64," + base64.b64encode(b).decode()
    companions = {}
    for key, entry in man.get("companions", {}).items():
        im = Image.open(os.path.join(ROOT, "art-src", entry["src"])).convert("RGB")
        w, h = im.size
        if w * 4 > h * 3:
            cw = h * 3 // 4; im = im.crop(((w - cw) // 2, 0, (w - cw) // 2 + cw, h))
        else:
            ch = w * 4 // 3; top = (h - ch) * 3 // 10; im = im.crop((0, top, w, top + ch))
        im = im.resize((240, 320), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "WEBP", quality=entry.get("quality", q), method=6)
        b = buf.getvalue()
        total += len(b)
        companions[key] = "data:image/webp;base64," + base64.b64encode(b).decode()
    rooms = {}
    for key, entry in man.get("rooms", {}).items():
        im = Image.open(os.path.join(ROOT, "art-src", entry["src"])).convert("RGB")
        s = min(im.size); l, tp = (im.size[0] - s) // 2, (im.size[1] - s) // 2
        im = im.crop((l, tp, l + s, tp + s)).resize((224, 224), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "WEBP", quality=entry.get("quality", q), method=6)
        b = buf.getvalue()
        total += len(b)
        rooms[key] = "data:image/webp;base64," + base64.b64encode(b).decode()
    block = "window.ZP_ART = " + json.dumps({"items": data, "scenes": scenes, "enemies": enemies, "companions": companions, "rooms": rooms}, separators=(",", ":")) + ";"
    path = os.path.join(ROOT, "index.html")
    html = open(path, encoding="utf-8").read()
    pat = re.compile(r"(<script id=\"zp-art\">/\* ART-DATA: generated by tools/build_art.py, do not edit \*/\n).*?(\n</script>)", re.S)
    if not pat.search(html):
        sys.exit("ART-DATA markers not found in index.html")
    html = pat.sub(lambda m: m.group(1) + block + m.group(2), html)
    open(path, "w", encoding="utf-8").write(html)
    print(f"{len(data)} item cards + {len(scenes)} scene(s) + {len(enemies)} enemy portrait(s) + {len(companions)} companion portrait(s) + {len(rooms)} room(s), {total // 1024} KB WebP ({len(block) // 1024} KB embedded)")
    if "--sheet" in sys.argv:
        out = sys.argv[sys.argv.index("--sheet") + 1]
        n = len(cards); cols = 6; rows = (n + cols - 1) // cols; t = 160
        sheet = Image.new("RGB", (cols * t, rows * t), (20, 20, 20))
        for i, (name, im) in enumerate(cards.items()):
            sheet.paste(im.resize((t - 6, t - 6)), ((i % cols) * t + 3, (i // cols) * t + 3))
        sheet.save(out)
        print("contact sheet:", out)

if __name__ == "__main__":
    main()
